/// Special token sequences used by ordinary user/assistant chat.
///
/// These are vocabulary IDs, not their textual spellings. This is important
/// for empty-string special tokens, which cannot be recovered by tokenizing
/// marker text.
#[derive(Clone, Debug)]
pub struct ChatConfig {
    pub user_start_ids: Vec<u16>,
    pub user_end_ids: Vec<u16>,
    pub assistant_start_ids: Vec<u16>,
    pub assistant_end_ids: Vec<u16>,
}

impl ChatConfig {
    pub fn new(
        user_start_ids: Vec<u16>,
        user_end_ids: Vec<u16>,
        assistant_start_ids: Vec<u16>,
        assistant_end_ids: Vec<u16>,
    ) -> Self {
        Self {
            user_start_ids,
            user_end_ids,
            assistant_start_ids,
            assistant_end_ids,
        }
    }

    fn validate(&self, lm: &LM) -> Result<(), String> {
        validate_token_sequence(lm, "user_start_ids", &self.user_start_ids)?;
        validate_token_sequence(lm, "user_end_ids", &self.user_end_ids)?;
        validate_token_sequence(lm, "assistant_start_ids", &self.assistant_start_ids)?;
        validate_token_sequence(lm, "assistant_end_ids", &self.assistant_end_ids)?;
        Ok(())
    }

    pub fn tinychat() -> Self {
        Self {
            user_start_ids: vec![0],
            user_end_ids: vec![2],
            assistant_start_ids: vec![1],
            assistant_end_ids: vec![2],
        }
    }
}

/// Stateful conversation context for one Chatter session.
///
/// The session owns the incremental inference state, so each call to
/// `Chatter::reply_ids` continues the same conversation. Create a new session
/// to start a separate conversation.
pub struct ChatSession {
    state: LMInferenceState,
    assistant_end_is_pending: bool,
}

pub struct Chatter {
    lm: LM,
    config: ChatConfig,
}

impl Chatter {
    pub fn new_result(lm: LM, config: ChatConfig) -> Result<Self, String> {
        config.validate(&lm)?;
        Ok(Self { lm, config })
    }

    pub fn new(lm: LM, config: ChatConfig) -> Self {
        match config.validate(&lm) {
            Ok(_o) => {}
            Err(e) => println!("{}", e)
        }
        Self { lm, config }
    }

    /// Start an independent conversation with fresh inference state.
    pub fn new_session(&self) -> Result<ChatSession, String> {
        Ok(ChatSession {
            state: self.lm.new_inference_state()?,
            assistant_end_is_pending: false,
        })
    }

    /// Add one user message and generate the assistant reply.
    ///
    /// The message content is supplied as token IDs. `ChatConfig` inserts the
    /// configured user/assistant role boundaries around those IDs, and the
    /// generated reply is returned as token IDs as well. No role marker is
    /// represented as text, so empty-string special tokens work normally.
    ///
    /// The assistant end marker is left unconsumed when generated. It is
    /// inserted at the beginning of the next user turn, preserving the
    /// configured conversation format without needing a special token to be
    /// decoded as text.
    pub fn reply_ids(
        &self,
        session: &mut ChatSession,
        user_ids: &[u16],
        max_gen_length: usize,
        temperature: f32,
    ) -> Result<Vec<u16>, String> {
        for &id in user_ids {
            if id as usize >= self.lm.vocab_size() {
                return Err(format!(
                    "User message contains token ID {}, but vocabulary size is {}",
                    id,
                    self.lm.vocab_size(),
                ));
            }
        }

        // Callers may supply an ID stream assembled from smaller token pieces.
        // Normalize it to the exact tokenizer segmentation used by training.
        let canonical_user_ids = self.lm.merge_token_ids(user_ids)?;

        let mut prompt_ids = Vec::with_capacity(
            canonical_user_ids.len()
                + self.config.user_start_ids.len()
                + self.config.user_end_ids.len()
                + self.config.assistant_start_ids.len()
                + if session.assistant_end_is_pending {
                self.config.assistant_end_ids.len()
            } else {
                0
            },
        );

        if session.assistant_end_is_pending {
            prompt_ids.extend_from_slice(&self.config.assistant_end_ids);
        }
        prompt_ids.extend_from_slice(&self.config.user_start_ids);
        prompt_ids.extend_from_slice(&canonical_user_ids);
        prompt_ids.extend_from_slice(&self.config.user_end_ids);
        prompt_ids.extend_from_slice(&self.config.assistant_start_ids);

        let logits = feed_ids(&self.lm, &mut session.state, &prompt_ids)?;

        let (assistant_ids, stop) = generate_until_markers(
            &self.lm,
            &mut session.state,
            &logits,
            max_gen_length,
            temperature,
            &[StopSequence {
                ids: &self.config.assistant_end_ids,
                stop: GenerationStop::MessageEnd,
            }],
        )?;

        // The end marker is withheld by generate_until_markers. On the next
        // turn, append it before the next user-role marker. A token-limit stop
        // is also treated as a closed assistant turn, matching the CLI's
        // previous behavior.
        session.assistant_end_is_pending = matches!(
            stop,
            GenerationStop::MessageEnd | GenerationStop::TokenLimit,
        );

        Ok(assistant_ids)
    }

    /// Convenience adapter for terminal use. The conversation API itself is
    /// token-ID based; text is tokenized only at this user-interface boundary
    /// and generated IDs are decoded only for display.
    pub fn start_chat_result(
        &self,
        max_gen_length: usize,
        temperature: f32,
        _threads: usize,
    ) -> Result<(), String> {
        let mut session = self.new_session()?;

        loop {
            print!("USER: ");
            io::stdout().flush().map_err(|e| e.to_string())?;

            let mut user = String::new();
            io::stdin().read_line(&mut user).map_err(|e| e.to_string())?;
            let user = user.trim_end_matches(&['\r', '\n'][..]);

            if user.trim() == "/exit" || user.trim() == "/quit" {
                break;
            }
            if user.trim().is_empty() {
                continue;
            }

            // Text is converted to token IDs once, at the terminal boundary.
            let user_ids = self.lm.tokenize_text(user);

            print!("BOT: ");
            io::stdout().flush().map_err(|e| e.to_string())?;
            let assistant_ids = self.reply_ids(
                &mut session,
                &user_ids,
                max_gen_length,
                temperature,
            )?;

            print!("{}", decode_ids(&self.lm, &assistant_ids));
            println!();
        }

        Ok(())
    }

    /// Convenience adapter for terminal use. The conversation API itself is
    /// token-ID based; text is tokenized only at this user-interface boundary
    /// and generated IDs are decoded only for display.
    pub fn start_chat(
        &self,
        max_gen_length: usize,
        temperature: f32,
        _threads: usize,
    ) {
        match self.start_chat_result(max_gen_length, temperature, _threads) {
            Ok(_o) => {}
            Err(e) => println!("ERROR in Chatter::start_chat() : {}", e)
        }
    }
}

