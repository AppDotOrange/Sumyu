fn validate_token_sequence(
    lm: &LM,
    name: &str,
    ids: &[u16],
) -> Result<(), String> {
    if ids.is_empty() {
        return Err(format!("{} cannot be empty", name));
    }

    let vocab_size = lm.vocab_size();
    for &id in ids {
        if id as usize >= vocab_size {
            return Err(format!(
                "{} contains token ID {}, but vocabulary size is {}",
                name, id, vocab_size
            ));
        }
    }

    Ok(())
}

fn validate_stop_sequences(
    stops: &[(&str, &[u16])],
) -> Result<(), String> {
    for (name, ids) in stops {
        if ids.is_empty() {
            return Err(format!("{} cannot be empty", name));
        }
    }

    for i in 0..stops.len() {
        for j in (i + 1)..stops.len() {
            let (a_name, a) = stops[i];
            let (b_name, b) = stops[j];

            if a == b || a.starts_with(b) || b.starts_with(a) {
                return Err(format!(
                    "Stop token sequences '{}' and '{}' must be distinct and neither may be a prefix of the other",
                    a_name, b_name
                ));
            }
        }
    }

    Ok(())
}

fn feed_ids(
    lm: &LM,
    state: &mut LMInferenceState,
    ids: &[u16],
) -> Result<Vec<f32>, String> {
    if ids.is_empty() {
        return Err("Cannot feed an empty token sequence".to_string());
    }

    let mut logits = Vec::new();
    for &id in ids {
        if id as usize >= lm.vocab_size() {
            return Err(format!("Token ID {} is outside the vocabulary", id));
        }
        logits = lm.forward_token_id(id, state);
    }

    Ok(logits)
}

fn decode_ids(lm: &LM, ids: &[u16]) -> String {
    let mut bytes = Vec::<u8>::new();

    for &id in ids {
        append_decoded_token_bytes(
            lm.token_text(id),
            &mut bytes,
        );
    }

    String::from_utf8_lossy(&bytes).into_owned()
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum GenerationStop {
    MessageEnd,
    ToolCallStart,
    ToolCallEnd,
    TokenLimit,
}

struct StopSequence<'a> {
    ids: &'a [u16],
    stop: GenerationStop,
}

/// Appends one sampled token to the raw generated stream, re-tokenizes it using
/// the model's training tokenizer, then replays only the not-yet-stable suffix.
///
/// `stable_state` is a snapshot immediately after `stable_prefix_len` canonical
/// tokens. The tokenizer's maximum token byte length guarantees that this
/// prefix cannot be changed by future generated bytes.
fn append_and_retokenize(
    lm: &LM,
    state: &mut LMInferenceState,
    logits: &mut Vec<f32>,
    stable_state: &mut LMInferenceState,
    stable_logits: &mut Vec<f32>,
    stable_prefix_len: &mut usize,
    raw_output_ids: &mut Vec<u16>,
    output_ids: &mut Vec<u16>,
    sampled_id: u16,
) -> Result<(), String> {
    raw_output_ids.push(sampled_id);
    let merged_ids = lm.merge_token_ids(raw_output_ids)?;
    let next_stable_prefix_len = lm.stable_token_prefix_len(&merged_ids);

    if next_stable_prefix_len < *stable_prefix_len
        || merged_ids.get(..*stable_prefix_len)
        != output_ids.get(..*stable_prefix_len)
    {
        return Err(
            "Tokenizer changed a previously stable generated-token prefix".to_string(),
        );
    }

    // Roll back only the unstable tokenizer suffix. Its maximum byte length is
    // bounded by the longest vocabulary token, not by the whole conversation.
    *state = (*stable_state).clone();
    *logits = (*stable_logits).clone();

    for index in *stable_prefix_len..merged_ids.len() {
        *logits = lm.forward_token_id(merged_ids[index], state);

        if index + 1 == next_stable_prefix_len {
            *stable_state = (*state).clone();
            *stable_logits = (*logits).clone();
        }
    }

    *stable_prefix_len = next_stable_prefix_len;
    *output_ids = merged_ids;
    Ok(())
}

/// Computes preview logits after an incomplete stop-marker prefix without
/// committing that prefix to the real conversation state. This is necessary
/// for multi-token control markers: the next marker ID must be sampled from the
/// state that includes the preceding marker IDs.
fn preview_pending_logits(
    lm: &LM,
    state: &LMInferenceState,
    logits: &[f32],
    stable_state: &LMInferenceState,
    stable_logits: &[f32],
    stable_prefix_len: usize,
    raw_output_ids: &[u16],
    output_ids: &[u16],
    pending: &[u16],
) -> Result<Vec<f32>, String> {
    let mut preview_state = (*state).clone();
    let mut preview_logits = logits.to_vec();
    let mut preview_stable_state = (*stable_state).clone();
    let mut preview_stable_logits = stable_logits.to_vec();
    let mut preview_stable_prefix_len = stable_prefix_len;
    let mut preview_raw_output_ids = raw_output_ids.to_vec();
    let mut preview_output_ids = output_ids.to_vec();

    for &id in pending {
        append_and_retokenize(
            lm,
            &mut preview_state,
            &mut preview_logits,
            &mut preview_stable_state,
            &mut preview_stable_logits,
            &mut preview_stable_prefix_len,
            &mut preview_raw_output_ids,
            &mut preview_output_ids,
            id,
        )?;
    }

    Ok(preview_logits)
}

/// Generates until a configured token-ID sequence appears.
///
/// Generated text pieces are continuously re-tokenized through the LM's
/// training tokenizer. The stable prefix is kept in the inference state while
/// only the bounded, still-mergeable tail is replayed when a new piece arrives.
/// This means e.g. `th` followed by `e` is fed onward as the single `the` token.
///
/// Logits are borrowed so callers can safely reuse their current logits value
/// after a generation phase (notably when an agent enters tool-call handling).
fn generate_until_markers(
    lm: &LM,
    state: &mut LMInferenceState,
    initial_logits: &[f32],
    max_gen_length: usize,
    temperature: f32,
    stops: &[StopSequence<'_>],
) -> Result<(Vec<u16>, GenerationStop), String> {
    if stops.is_empty() {
        return Err("At least one generation stop sequence is required".to_string());
    }

    let mut logits = initial_logits.to_vec();
    let mut sampling_logits = logits.clone();
    let mut output_ids = Vec::<u16>::new();
    let mut raw_output_ids = Vec::<u16>::new();
    let mut pending = Vec::<u16>::new();

    // The stable snapshot is the rollback point for the tokenizer's trailing
    // suffix. `state` itself may be ahead of this point by at most the unstable
    // suffix length.
    let mut stable_state = (*state).clone();
    let mut stable_logits = logits.clone();
    let mut stable_prefix_len = 0usize;

    for _ in 0..max_gen_length {
        let token_id = lm.sample_next_token(&sampling_logits, temperature);
        pending.push(token_id);

        // Stop markers are tested on sampled IDs before text re-tokenization.
        // The marker itself is withheld; the caller decides how to append it.
        if let Some(stop) = stops.iter().find(|candidate| {
            pending.as_slice() == candidate.ids
        }) {
            return Ok((output_ids, stop.stop));
        }

        // Keep any suffix that could still be the beginning of a control marker.
        while !pending.is_empty()
            && !stops.iter().any(|candidate| candidate.ids.starts_with(&pending))
        {
            let safe_id = pending.remove(0);
            append_and_retokenize(
                lm,
                state,
                &mut logits,
                &mut stable_state,
                &mut stable_logits,
                &mut stable_prefix_len,
                &mut raw_output_ids,
                &mut output_ids,
                safe_id,
            )?;
        }

        sampling_logits = if pending.is_empty() {
            logits.clone()
        } else {
            preview_pending_logits(
                lm,
                state,
                &logits,
                &stable_state,
                &stable_logits,
                stable_prefix_len,
                &raw_output_ids,
                &output_ids,
                &pending,
            )?
        };
    }

    // An unfinished prefix of a configured stop marker is discarded. It was
    // never added to the model state, so the state remains aligned with output_ids.
    Ok((output_ids, GenerationStop::TokenLimit))
}

fn read_capped<R: Read>(
    mut reader: R,
    max_bytes: usize,
) -> io::Result<(Vec<u8>, bool)> {
    let mut output = Vec::with_capacity(max_bytes.min(8192));
    let mut buffer = [0u8; 8192];
    let mut truncated = false;

    loop {
        let read = reader.read(&mut buffer)?;
        if read == 0 {
            break;
        }

        let remaining = max_bytes.saturating_sub(output.len());
        let keep = remaining.min(read);
        output.extend_from_slice(&buffer[..keep]);
        if keep < read {
            truncated = true;
        }
    }

    Ok((output, truncated))
}

